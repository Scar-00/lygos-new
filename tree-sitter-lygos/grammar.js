const PREC = { assign: 1, or: 2, and: 3, equality: 4, compare: 5, add: 6, multiply: 7, unary: 8, postfix: 9 };

module.exports = grammar({
  name: 'lygos',
  word: $ => $.identifier,
  extras: $ => [/\s/, $.line_comment, $.block_comment],
  externals: $ => [$.block_comment],
  supertypes: $ => [$._expression, $._type],
  inline: $ => [$._type_identifier],
  conflicts: $ => [[$.scoped_type_identifier, $._expression]],

  rules: {
    source_file: $ => repeat(choice($._declaration, $._statement)),
    _declaration: $ => choice($.function_declaration, $.struct_declaration, $.enum_declaration,
      $.trait_declaration, $.impl_declaration, $.type_alias, $.static_declaration, $.macro_definition,
      $.comptime_function, $.attributed_declaration, $.import_declaration),

    import_declaration: $ => seq('import', field('source', choice($.identifier, $.string_literal)),
      optional(seq('as', field('alias', $.identifier))), ';'),

    comptime_function: $ => seq('macro', $.function_declaration),
    attributed_declaration: $ => seq(repeat1($.attribute), choice($.function_declaration,
      $.struct_declaration, $.enum_declaration, $.trait_declaration, $.impl_declaration,
      $.type_alias, $.static_declaration)),
    attribute: $ => seq('#', '[', field('name', $.identifier), optional($.macro_arguments), ']'),

    function_declaration: $ => seq('fn', field('name', $.identifier), field('parameters', $.parameters),
      optional(seq('->', field('return_type', $._type))), choice(field('body', $.block), ';')),
    parameters: $ => seq('(', commaSep(choice($.parameter, $.self_parameter)), ')'),
    parameter: $ => seq(field('name', $.identifier), ':', field('type', $._type)),
    self_parameter: $ => seq(optional(choice('mut', seq('&', optional('mut')))), $.self),
    self: _ => 'self',
    block: $ => seq('{', repeat($._statement), '}'),

    struct_declaration: $ => seq('struct', field('name', $._type_identifier), '{', repeat($.field_declaration), '}'),
    field_declaration: $ => seq(field('name', $.identifier), ':', field('type', $._type), ';'),
    enum_declaration: $ => seq('enum', field('name', $._type_identifier),
      optional(seq(':', field('type', $._type))), '{', commaSep($.enum_variant), '}'),
    enum_variant: $ => field('name', $.identifier),
    trait_declaration: $ => seq('trait', field('name', $._type_identifier), '{', repeat($.function_declaration), '}'),
    impl_declaration: $ => seq('impl', optional(seq(field('trait', choice($._type_identifier, $.scoped_type_identifier)), 'for')),
      field('type', choice($._type_identifier, $.scoped_type_identifier)), '{', repeat($.function_declaration), '}'),
    type_alias: $ => seq('type', field('name', $._type_identifier), '=', field('type', $._type), ';'),
    static_declaration: $ => seq('static', field('name', $.identifier), ':', field('type', $._type),
      optional(seq('=', field('value', $._expression))), ';'),

    _type: $ => choice($._type_identifier, $.scoped_type_identifier, $.primitive_type, $.pointer_type, $.reference_type,
      $.array_type, $.slice_type, $.function_type),
    _type_identifier: $ => alias($.identifier, $.type_identifier),
    scoped_type_identifier: $ => seq(repeat1(seq($.identifier, '::')), $._type_identifier),
    primitive_type: _ => choice('void', 'bool', 'str', 'i8', 'i16', 'i32', 'i64', 'u8', 'u16', 'u32', 'u64', 'f32', 'f64'),
    pointer_type: $ => seq('*', field('qualifier', choice('const', 'mut')), field('type', $._type)),
    reference_type: $ => seq('&', optional('mut'), field('type', $._type)),
    array_type: $ => seq('[', field('type', $._type), ';', field('length', $.integer_literal), ']'),
    slice_type: $ => seq('[', field('type', $._type), ']'),
    function_type: $ => seq('fn', '(', commaSep($._type), ')', optional(seq('->', field('return_type', $._type)))),

    _statement: $ => choice($.let_declaration, $.expression_statement, $.return_statement,
      $.break_statement, $.if_statement, $.for_statement),
    let_declaration: $ => seq($._let, ';'),
    _let: $ => seq('let', optional('mut'), field('name', $.identifier),
      choice(seq(':', field('type', $._type), optional(seq('=', field('value', $._expression)))),
        seq('=', field('value', $._expression)))),
    expression_statement: $ => seq($._expression, ';'),
    return_statement: $ => seq('return', optional($._expression), ';'),
    break_statement: _ => seq('break', ';'),
    if_statement: $ => seq('if', field('condition', $._expression), field('consequence', $.block),
      optional(seq('else', field('alternative', choice($.block, $.if_statement))))),
    for_statement: $ => seq('for', field('initializer', alias($._let, $.let_declaration)), 'in',
      field('condition', $._expression), field('body', $.block)),

    _expression: $ => choice($.identifier, $.self, $.integer_literal, $.float_literal,
      $.string_literal, $.char_literal, $.array_expression, $.struct_expression,
      $.parenthesized_expression, $.unary_expression, $.cast_expression, $.binary_expression,
      $.assignment_expression, $.call_expression, $.index_expression, $.field_expression,
      $.scoped_expression, $.macro_invocation),
    parenthesized_expression: $ => seq('(', $._expression, ')'),
    array_expression: $ => seq('[', choice(
      commaSep($._expression),
      seq(field('value', $._expression), ';', field('length', $.integer_literal))
    ), ']'),
    struct_expression: $ => seq(field('type', choice($._type_identifier, $.scoped_type_identifier)), '$', '{',
      commaSep(choice($.field_initializer, $._expression)), '}'),
    field_initializer: $ => seq('.', field('name', $.identifier), '=', field('value', $._expression)),
    unary_expression: $ => prec(PREC.unary, seq(field('operator', choice('!', '*', '+', '-', seq('&', optional('mut')))),
      field('argument', $._expression))),
    cast_expression: $ => prec(PREC.unary, seq('(', ':', field('type', $._type), ')', field('value', $._expression))),
    binary_expression: $ => choice(...[
      [PREC.or, '||'], [PREC.and, '&&'], [PREC.equality, choice('==', '!=')],
      [PREC.compare, choice('<', '>', '<=', '>=')], [PREC.add, choice('+', '-')],
      [PREC.multiply, choice('*', '/', '%')],
    ].map(([precedence, operator]) => prec.left(precedence,
      seq(field('left', $._expression), field('operator', operator), field('right', $._expression))))),
    assignment_expression: $ => prec.right(PREC.assign,
      seq(field('left', $._expression), '=', field('right', $._expression))),
    call_expression: $ => prec(PREC.postfix, seq(field('function', $._expression), field('arguments', $.arguments))),
    arguments: $ => seq('(', commaSep($._expression), ')'),
    index_expression: $ => prec(PREC.postfix, seq(field('value', $._expression), '[', field('index', $._expression), ']')),
    field_expression: $ => prec(PREC.postfix, seq(field('value', $._expression),
      field('operator', choice('.', '->')), field('field', $.identifier))),
    scoped_expression: $ => prec(PREC.postfix, seq(field('path', $._expression), '::', field('name', $.identifier))),

    macro_definition: $ => seq('macro', field('name', $.identifier), '{', repeat($.macro_arm), '}'),
    macro_arm: $ => seq($.macro_parameters, '->', field('body', $.token_tree)),
    macro_parameters: $ => seq('(', commaSep($.macro_parameter), ')'),
    macro_parameter: $ => seq(field('name', $.identifier), ':', '$', optional(seq('[', ']'))),
    macro_invocation: $ => seq(field('name', choice($.identifier, $.scoped_expression)), '$', field('arguments', $.macro_arguments)),
    macro_arguments: $ => seq('(', repeat($._token_tree), ')'),
    token_tree: $ => choice(seq('(', repeat($._token_tree), ')'), seq('[', repeat($._token_tree), ']'),
      seq('{', repeat($._token_tree), '}')),
    _token_tree: $ => choice($.token_tree, $.macro_variable, $.identifier, $.self, $.primitive_type,
      $.integer_literal, $.float_literal, $.string_literal, $.char_literal, $._macro_keyword,
      ',', ';', ':', '.', '$', '#', '|', '->', '::', '=', '+', '-', '*', '/', '%', '&', '!',
      '==', '!=', '<', '>', '<=', '>=', '||', '&&'),
    macro_variable: $ => prec(1, seq('$', $.identifier)),
    _macro_keyword: _ => choice('let', 'mut', 'const', 'struct', 'if', 'else', 'for', 'fn', 'return',
      'in', 'impl', 'type', 'static', 'trait', 'macro', 'enum', 'break'),

    identifier: _ => /[_\p{L}][_\p{L}\p{N}]*/u,
    integer_literal: _ => /[0-9]+/,
    float_literal: _ => /[0-9]+\.[0-9]+/,
    string_literal: $ => seq('"', repeat(choice($.escape_sequence, token.immediate(/[^"\\]+/))), '"'),
    char_literal: $ => seq("'", repeat(choice($.escape_sequence, token.immediate(/[^'\\]+/))), "'"),
    escape_sequence: _ => token.immediate(/\\./),
    line_comment: _ => token(seq('//', /[^\n\r]*/)),
  },
});

function commaSep(rule) {
  return optional(seq(rule, repeat(seq(',', rule)), optional(',')));
}
